/** 把任意存储值解析为一个可渲染的图标 key */
export function resolveGroupIcon(key?: string): string {
  if (!key) return DEFAULT_GROUP_ICON;
  if (key in GROUP_ICONS) return key;
  const k = key.startsWith('if:') ? `icon-${key.slice(3)}` : key;
  return LEGACY[k] ?? DEFAULT_GROUP_ICON;
}
